[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$resourcePath = Join-Path $root 'Crimson.Core\Resources\UiStrings.resx'
$outputPath = Join-Path $root 'Crimson.Core\Resources\UiStrings.cs'
[xml]$resources = [IO.File]::ReadAllText($resourcePath)
$keys = @($resources.root.data | ForEach-Object { [string]$_.name } | Sort-Object -CaseSensitive)
$seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
foreach ($key in $keys) {
    if ($key -notmatch '^[A-Z][A-Za-z0-9_]*$' -or -not $seen.Add($key)) {
        throw "UI resource keys must be unique C# property names: $key"
    }
}

$lines = [Collections.Generic.List[string]]::new()
@(
    '// <auto-generated />'
    '// Regenerate with scripts/update-ui-strings.ps1 after changing resource keys.'
    '#nullable enable'
    'using System.Globalization;'
    'using System.Resources;'
    ''
    'namespace Crimson.Resources;'
    ''
    'public static class UiStrings'
    '{'
    '    private static readonly ResourceManager Manager = new("Crimson.Resources.UiStrings", typeof(UiStrings).Assembly);'
    ''
    '    private static string Get(string name) => Manager.GetString(name, CultureInfo.CurrentUICulture)'
    '        ?? throw new MissingManifestResourceException($"Missing UI resource: {name}");'
    ''
    '    public static string Format(string format, params object?[] arguments) =>'
    '        string.Format(CultureInfo.CurrentCulture, format, arguments);'
    ''
) | ForEach-Object { $lines.Add($_) }
foreach ($key in $keys) {
    $lines.Add("    public static string $key => Get(nameof($key));")
}
$lines.Add('}')
[IO.File]::WriteAllText($outputPath, ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
Write-Host "Generated $($keys.Count) UI string accessors."
